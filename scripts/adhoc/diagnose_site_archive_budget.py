#!/usr/bin/env python3
"""Reproduce native archive-only budget diagnostics for #463 (2026-11-16).

Inputs: exact repository commit, its unchanged generated site, proposed archive
byte/file caps. Output: JSON native old/proposed contract results and headroom.
No rendering, guard edits, source edits, fetch, provider call or Git mutation.
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import stat
from pathlib import Path

from audit_site_archive_growth import git, tree

from dufmech import site_contract


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--site", type=Path, required=True)
    parser.add_argument("--site-prefix", default="pages/")
    parser.add_argument("--total-bytes", type=int, required=True)
    parser.add_argument("--file-count", type=int, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root, site = args.repo.resolve(), args.site.resolve()
    if site == args.output.resolve() or site in args.output.resolve().parents:
        raise ValueError("diagnostic output must be outside the generated site")
    relative = args.site_prefix
    if not relative or relative.startswith("/") or not relative.endswith("/") or ".." in Path(relative).parts:
        raise ValueError("invalid Git site prefix")
    commit = git(root, "rev-parse", args.commit + "^{commit}").decode().strip()
    expected = {path.removeprefix(relative): entry for path, entry in tree(root, commit).items()
                if path.startswith(relative)}
    actual = {}
    for path in site.rglob("*"):
        if path.is_symlink():
            raise ValueError("symlink site entry refused")
        if path.is_dir():
            continue
        if not stat.S_ISREG(path.stat().st_mode):
            raise ValueError("nonregular site entry refused")
        actual[path.relative_to(site).as_posix()] = path
    if set(actual) != set(expected):
        raise ValueError("generated file inventory differs from the measured commit")
    for name, path in actual.items():
        raw = path.read_bytes()
        oid = hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()
        mode = "100755" if path.stat().st_mode & 0o111 else "100644"
        if (oid != expected[name]["oid"] or len(raw) != expected[name]["size"]
                or mode != expected[name]["mode"]):
            raise ValueError("generated bytes differ from measured commit: " + name)
    native = root / "src/dufmech/site_contract.py"
    if native.read_bytes() != git(root, "show", commit + ":src/dufmech/site_contract.py"):
        raise ValueError("native contract differs from the measured commit")
    executed = Path(site_contract.__file__).read_bytes()
    if executed != native.read_bytes():
        raise ValueError("executed native contract differs from verified source bytes")
    old = json.loads(git(root, "show", commit + ":conf/pages_budgets.json"))
    proposed = {**old, "site_total_bytes": args.total_bytes, "generated_file_count": args.file_count}
    old_errors, measurements = site_contract.check_site(site, old)
    proposed_errors, again = site_contract.check_site(site, proposed)
    if measurements != again:
        raise ValueError("site changed between native checks")
    report = {"checked_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
              "measured_commit": commit,
              "helper_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "site_contract_sha256": hashlib.sha256(native.read_bytes()).hexdigest(),
              "executed_contract_sha256": hashlib.sha256(executed).hexdigest(),
              "site_git_prefix": relative,
              "scope": "Archive-only capacity diagnostic before separate source-list pagination; remaining HTML failure is issue464.",
              "old_budgets": old, "proposed_budgets": proposed, "measurements": measurements,
              "generated_files": len(actual), "old_errors": old_errors,
              "proposed_errors": proposed_errors,
              "headroom": {"bytes": args.total_bytes - measurements["total_bytes"],
                           "files": args.file_count - len(actual)}}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"old_errors": old_errors, "proposed_errors": proposed_errors,
                      "headroom": report["headroom"]}, indent=2))


if __name__ == "__main__":
    main()
